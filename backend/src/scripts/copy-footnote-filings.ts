const SOURCE_DIRS = [
  path.resolve(__dirname, "../data_source/sec/output/ex-21_2025"),
  path.resolve(__dirname, "../data_source/sec/output/ex-8_2025"),
];

const TARGET_DIR = path.resolve(
  __dirname,
  "../data_source/sec/output/subsidiaries_footnote_2025"
);

async function main() {
  logger.info(`Copying ${ACCESSION_NUMBERS.length} filings with footnotes...`);

  // Create target directory
  await fs.mkdir(TARGET_DIR, { recursive: true });
  logger.info(`Created target directory: ${TARGET_DIR}`);

  let copied = 0;
  let notFound = 0;
  const missing: string[] = [];

  for (const accession of ACCESSION_NUMBERS) {
    let found = false;

    // Try each source directory
    for (const sourceDir of SOURCE_DIRS) {
      try {
        const files = await fs.readdir(sourceDir);

        // Find file matching this accession
        const matchingFile = files.find((f) => f.includes(accession));

        if (matchingFile) {
          const sourcePath = path.join(sourceDir, matchingFile);
          const targetPath = path.join(TARGET_DIR, matchingFile);

          await fs.copyFile(sourcePath, targetPath);
          copied++;
          found = true;
          logger.info(`[${copied}/${ACCESSION_NUMBERS.length}] Copied: ${matchingFile}`);
          break;
        }
      } catch (error) {
        // Directory might not exist, continue
        continue;
      }
    }

    if (!found) {
      notFound++;
      missing.push(accession);
      logger.warn(`Not found: ${accession}`);
    }
  }

  logger.info(`\nCopy complete:`);
  logger.info(`  Copied: ${copied}`);
  logger.info(`  Not found: ${notFound}`);

  if (missing.length > 0) {
    logger.warn(`\nMissing accessions (${missing.length}):`);
    missing.forEach((acc) => logger.warn(`  ${acc}`));
  }
}

if (require.main === module) {
  main().catch((error) => {
    logger.error("Fatal error", { error: error.message });
    console.error(error);
    process.exit(1);
  });
}
